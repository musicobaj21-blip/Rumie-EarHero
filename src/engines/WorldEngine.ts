export const ALL_LEVELS: LevelDefinition[] = WORLDS.flatMap((w) => w.levels);

export const WorldEngine = {
  getWorlds(): WorldDefinition[] {
    return WORLDS;
  },

  getWorldById(worldId: number): WorldDefinition | undefined {
    return WORLDS.find((w) => w.id === worldId);
  },

  getLevelById(levelId: string): LevelDefinition | undefined {
    return ALL_LEVELS.find((l) => l.id === levelId);
  },

  getNextLevel(levelId: string): LevelDefinition | null {
    const idx = ALL_LEVELS.findIndex((l) => l.id === levelId);
    if (idx < 0 || idx >= ALL_LEVELS.length - 1) return null;
    return ALL_LEVELS[idx + 1];
  },

  /**
   * Determines whether a level is unlocked based on BOTH student progress AND active license.
   */
  getLevelAccessStatus(
    level: LevelDefinition,
    progress: UserProgress,
    qaUnlockAll = false
  ): 'completed' | 'current' | 'available' | 'locked-progress' | 'locked-license' {
    const levelProg = progress.levels[level.id];
    const idx = ALL_LEVELS.findIndex((l) => l.id === level.id);
    const prevCompleted =
      idx === 0 || Boolean(progress.levels[ALL_LEVELS[idx - 1].id]?.completed);

    if (qaUnlockAll) {
      if (levelProg?.completed) {
        return 'completed';
      }
      return prevCompleted ? 'current' : 'available';
    }

    const licenseAllowed = LicenseAdapter.canAccessWorld(level.worldId, progress.licensePlan);
    if (!licenseAllowed) {
      return 'locked-license';
    }

    if (levelProg?.completed) {
      return 'completed';
    }

    if (prevCompleted) {
      return 'current';
    }

    return 'locked-progress';
  },

  getCurrentActiveLevel(progress: UserProgress): LevelDefinition {
    for (const level of ALL_LEVELS) {
      const status = this.getLevelAccessStatus(level, progress);
      if (status === 'current') return level;
    }
    // If all accessible levels are completed, return last accessible level
    const accessible = ALL_LEVELS.filter((l) =>
      LicenseAdapter.canAccessWorld(l.worldId, progress.licensePlan)
    );
    return accessible[accessible.length - 1] ?? ALL_LEVELS[0];
  },

  getWorldStats(world: WorldDefinition, progress: UserProgress) {
    let completedCount = 0;
    let earnedStars = 0;
    const maxStars = world.levels.length * 3;
    for (const lvl of world.levels) {
      const lp = progress.levels[lvl.id];
      if (lp?.completed) completedCount += 1;
      earnedStars += lp?.stars ?? 0;
    }
    return {
      completedCount,
      totalCount: world.levels.length,
      earnedStars,
      maxStars,
      isCompleted: completedCount === world.levels.length,
      percent: Math.round((completedCount / world.levels.length) * 100),
    };
  },

  getGlobalCompletionPercent(progress: UserProgress): number {
    const completed = ALL_LEVELS.filter((l) => progress.levels[l.id]?.completed).length;
    return Math.round((completed / ALL_LEVELS.length) * 100);
  },

  getTotalStars(progress: UserProgress): number {
    return Object.values(progress.levels).reduce((sum, lp) => sum + (lp.stars ?? 0), 0);
  },
};
